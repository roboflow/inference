"""Run results, output-group results and V1-shaped output rows.

A ``RunResult`` (passive run) and a ``GroupResult`` (one output group of one
source pulse) hold one buffer entry per *selected port*. A plain workflow
output selects one port under its own name; a wildcard ``$steps.x.*`` selects
every output of ``x`` as ``<name>/<output>``, so ports with different layouts
keep their own layout and metadata. Both results are built by the same code
over a sequence of ``PlannedWorkflowOutput`` declarations: the plan's flat
outputs for a run, a group's fields for a group.

Rows follow V1's output construction::

    no grouped port                 [ {name: value, ...} ]
    top axis of a workflow input    one row per index of that axis
    top axis generated by a step    whole nested list copied into every row
    scalar port                     same value in every row
    nested positions                lists placed by index; a filtered or
                                    missing leaf is None, a filtered group []
    wildcard                        {output: value} at the ports' common
                                    axes; deeper axes stay nested lists

Values pass through ``Kind.to_output`` (with the declaration's options) and,
when serializing, ``Kind.to_serialized``. For a union of kinds, the first kind
whose hook succeeds wins, as in V1. After all hooks fail, a hook-free kind
only permits pass-through when its validator accepts the payload.
"""

